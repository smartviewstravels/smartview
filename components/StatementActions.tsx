"use client";

import { useState } from "react";
import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";

export interface StatementRow {
  service: string;
  total: number;
  paid: number;
  pending: number;
  dueDate: string;
  status: string;
}

export interface StatementData {
  customerName: string;
  customerPhone: string | null;
  customerCnic: string | null;
  statementDate: string;
  rows: StatementRow[];
  totalAmount: number;
  totalPaid: number;
  totalPending: number;
}

const NAVY: [number, number, number] = [30, 35, 77];
const GOLD: [number, number, number] = [201, 162, 39];

function pkr(n: number): string {
  return `PKR ${Math.round(n).toLocaleString("en-PK")}`;
}

function slug(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 40);
}

async function logoDataUrl(): Promise<string> {
  const res = await fetch("/logo.png");
  const blob = await res.blob();
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(String(reader.result));
    reader.onerror = () => reject(new Error("Could not load the logo."));
    reader.readAsDataURL(blob);
  });
}

/** Builds the branded statement PDF. Shared by Download and Share. */
async function buildPdf(data: StatementData): Promise<{
  blob: Blob;
  filename: string;
}> {
  const logo = await logoDataUrl();
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const pageWidth = doc.internal.pageSize.getWidth();

  // Header: logo + business name + tagline.
  doc.addImage(logo, "PNG", 14, 10, 24, 24);
  doc.setTextColor(...NAVY);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text("Smart View Travel", 42, 18);
  doc.setTextColor(...GOLD);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.text("Your Journey Our Passion", 42, 25);
  doc.setTextColor(...NAVY);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);
  doc.text("ACCOUNT STATEMENT", pageWidth - 14, 18, { align: "right" });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.text(`Date: ${data.statementDate}`, pageWidth - 14, 25, {
    align: "right",
  });

  // Navy divider.
  doc.setDrawColor(...NAVY);
  doc.setLineWidth(0.8);
  doc.line(14, 38, pageWidth - 14, 38);

  // Customer block.
  let y = 48;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.text("Billed to:", 14, y);
  y += 7;
  doc.setFontSize(12);
  doc.text(data.customerName, 14, y);
  y += 7;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(90, 90, 90);
  const details = [
    data.customerPhone ? `Phone: ${data.customerPhone}` : null,
    data.customerCnic ? `CNIC / Passport: ${data.customerCnic}` : null,
    `Records: ${data.rows.length}`,
  ]
    .filter(Boolean)
    .join("   |   ");
  doc.text(details, 14, y);
  doc.setTextColor(...NAVY);

  // Records table.
  autoTable(doc, {
    startY: y + 8,
    head: [["Service", "Total", "Paid", "Pending", "Due date", "Status"]],
    body: data.rows.map((r) => [
      r.service,
      pkr(r.total),
      pkr(r.paid),
      pkr(r.pending),
      r.dueDate,
      r.status,
    ]),
    headStyles: { fillColor: NAVY, textColor: [255, 255, 255] },
    columnStyles: {
      1: { halign: "right" },
      2: { halign: "right" },
      3: { halign: "right" },
      4: { halign: "center" },
      5: { halign: "center" },
    },
    styles: { fontSize: 10 },
  });

  // Totals.
  const afterTable = (doc as unknown as { lastAutoTable: { finalY: number } })
    .lastAutoTable.finalY;
  let ty = afterTable + 10;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.text(`Total: ${pkr(data.totalAmount)}`, 14, ty);
  ty += 7;
  doc.text(`Paid: ${pkr(data.totalPaid)}`, 14, ty);
  ty += 7;
  doc.text(`Pending: ${pkr(data.totalPending)}`, 14, ty);

  // Footer.
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(120, 120, 120);
  doc.text(
    "Generated by Smart View Travel — Your Journey Our Passion",
    pageWidth / 2,
    doc.internal.pageSize.getHeight() - 10,
    { align: "center" },
  );

  const filename = `Smart-View-Statement-${slug(data.customerName)}-${data.statementDate.replaceAll("/", "-")}.pdf`;
  return { blob: doc.output("blob"), filename };
}

function downloadBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

/**
 * Download + Share actions for a customer statement. Share uses the Web
 * Share API with the PDF file when the browser supports it (mobile);
 * otherwise it falls back to downloading.
 */
export default function StatementActions({ data }: { data: StatementData }) {
  const [busy, setBusy] = useState<"download" | "share" | null>(null);
  const [note, setNote] = useState<string | null>(null);

  async function download(): Promise<void> {
    setBusy("download");
    setNote(null);
    try {
      const { blob, filename } = await buildPdf(data);
      downloadBlob(blob, filename);
    } catch {
      setNote("Could not build the PDF. Please try again.");
    }
    setBusy(null);
  }

  async function share(): Promise<void> {
    setBusy("share");
    setNote(null);
    try {
      const { blob, filename } = await buildPdf(data);
      const file = new File([blob], filename, { type: "application/pdf" });
      if (navigator.canShare && navigator.canShare({ files: [file] })) {
        await navigator.share({
          files: [file],
          title: "Smart View Travel — Account Statement",
          text: `Account statement for ${data.customerName}`,
        });
      } else {
        downloadBlob(blob, filename);
        setNote(
          "Sharing is not supported on this browser — the PDF was downloaded instead.",
        );
      }
    } catch {
      setNote("Could not share the PDF. Try downloading it instead.");
    }
    setBusy(null);
  }

  return (
    <div>
      <button
        type="button"
        className="btn btn-primary"
        onClick={() => void download()}
        disabled={busy !== null}
      >
        {busy === "download" ? "Building PDF..." : "Download PDF"}
      </button>{" "}
      <button
        type="button"
        className="btn"
        onClick={() => void share()}
        disabled={busy !== null}
      >
        {busy === "share" ? "Preparing..." : "Share"}
      </button>
      {note && (
        <p className="note" style={{ marginTop: 8 }}>
          {note}
        </p>
      )}
    </div>
  );
}
